/**
 * The default out-of-box watchface's *unsigned* pieces (examples/
 * watchfaces/default) - manifest.json text and QuickJS bytecode, not a
 * pre-signed .comp (contrast store_install_selftest_pkg.h, which embeds
 * a package already signed with the fixed KALIBER_STORE_HMAC_KEY_
 * OVERRIDE test key). docs/design/launcher-states.md §4's actual
 * resolution: sign these at first boot with THIS device's own
 * get_hmac_key() output, assemble a tar container, install through the
 * unmodified kb_store_install() path - see
 * kb_store_install_default_face() (app_store.c). No fixed key baked in
 * anywhere, so this can be committed to the public repo like any other
 * example, and verifies on every real device, not just ones sharing one
 * override key.
 *
 * Regenerate after editing examples/watchfaces/default/app.js or its
 * manifest.json:
 *   QJSC=/tmp/qjs-host-build/qjsc python3 - <<'PYEOF'
 *   import sys, os, json, tempfile
 *   sys.path.insert(0, "tools/atelier")
 *   import atelier
 *   appdir = "examples/watchfaces/default"
 *   mf = atelier.load_manifest(appdir)
 *   with tempfile.TemporaryDirectory() as tmp:
 *       qjb = os.path.join(tmp, "app.qjb")
 *       entries = {"quickjs": "app.qjb"} if atelier.compile_quickjs(
 *           os.path.join(appdir, "app.js"), qjb) else {}
 *       mf["entries"] = entries
 *       mpath = os.path.join(tmp, "manifest.json")
 *       json.dump(mf, open(mpath, "w"), indent=2)
 *       open("/tmp/default_manifest.json", "wb").write(open(mpath, "rb").read())
 *       open("/tmp/default_app.qjb", "wb").write(open(qjb, "rb").read())
 *   PYEOF
 * then turn both /tmp files into byte arrays and paste them in below.
 */
